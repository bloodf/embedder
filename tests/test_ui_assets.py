"""Built wheel ships the compiled Vue page, with the shared icon set compiled in and no unresolved placeholders."""

import hashlib
import json
import re
import struct
import sys
import tempfile
import unittest
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import build  # noqa: E402

UI = ROOT / "src" / "embedder" / "ui"
MAX_BUILT_BYTES = 420_000   # the wheel measures ~408 kB with three.js, OrbitControls, the panel and five languages (page ~1.32 MB raw, deflated)
SHARED_ICONS = ROOT / "ui" / "shared" / "src" / "icons.ts"
ICON_SHA256 = "8b8ba319c366cd057788b1a4f0717395c2022e7625a2bd02d78d32077b2470f0"   # src/embedder/ui/icon.png


class UiAssets(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.artifact = build.build(out_dir=Path(tempfile.mkdtemp()))
        with zipfile.ZipFile(cls.artifact) as z:
            cls.text = z.read("embedder/_assets.py").decode("utf-8")

    @staticmethod
    def shared_icon(name):
        """The drawing of one icon of the shared set, as the attribute strings the compiled page carries."""
        line = re.search(r"^export const %s: OuiIconData = (\[.*\]);$" % name, SHARED_ICONS.read_text("utf-8"), re.M)
        return [str(v) for _, attrs in json.loads(line.group(1)) for v in attrs.values() if isinstance(v, str)]

    def test_every_error_and_block_code_is_translated(self):
        """Codes raised in Python reach the page as err.<code> (refusals) or block.<code> (plan blocks)."""
        source = "".join(p.read_text("utf-8") for p in (ROOT / "src" / "embedder").glob("*.py"))
        core = ROOT / "ui" / "src" / "core"
        tables = {"en and pt-BR": 2, "messages-es": 1, "messages-de": 1, "messages-zh": 1}
        texts = {name: (core / ("messages.ts" if name == "en and pt-BR" else name + ".ts")).read_text("utf-8") for name in tables}
        errors = set(re.findall(r'(?:SessionError|ThreeMFError|PresetError|CommandError)\("([a-z_]+)"', source))
        blocks = set(re.findall(r'Blocked\("([a-z_]+)"', source))
        for prefix, codes in (("err", errors), ("block", blocks)):
            for code in sorted(codes):
                for name, count in tables.items():
                    self.assertEqual(texts[name].count("'%s.%s':" % (prefix, code)), count, "%s.%s in %s" % (prefix, code, name))

    def test_the_wheel_carries_the_committed_page(self):
        html = build.page_html("app.html")
        self.assertEqual(html, (UI / "app.html").read_text("utf-8"))
        self.assertIn(repr(html), self.text)   # the wheel carries exactly this page

    def test_no_loose_icon_files_are_shipped(self):
        """Icons come compiled into the page from the shared set; the plugin folder keeps only the page and its mark."""
        self.assertEqual(sorted(p.name for p in UI.iterdir()), ["app.html", "icon.png"])
        self.assertNotRegex((UI / "app.html").read_text("utf-8"), r"\b(?:icon|spot)/[a-z0-9-]+\b(?!\.)")

    def test_committed_page_is_the_recorded_vue_build(self):
        """src/embedder/ui/app.html is generated by `npm run build` in ui/; a hand edit or a stale build fails here."""
        info = json.loads((ROOT / "ui" / "build.json").read_text("utf-8"))
        data = (UI / "app.html").read_bytes()
        self.assertEqual(hashlib.sha256(data).hexdigest(), info["sha256"])
        html = data.decode("utf-8")
        self.assertEqual(html.count("__BOOT__"), 1)
        self.assertNotIn("__ICONS__", html)
        self.assertIn('id="embedder-boot"', html)
        self.assertNotIn('id="embedder-icons"', html)
        self.assertNotIn("u1-boot", html)
        self.assertNotRegex(html, r"<script[^>]+src=|<link[^>]+href=\"https?:|@import\s*(?:url\(|['\"])|url\(https?:")
        self.assertNotRegex(html, r"\bnew Function\b|\beval\(")
        self.assertIn("__VUE_OPTIONS_API__", (ROOT / "ui" / "vite.config.ts").read_text("utf-8"))

    def test_page_has_no_sibling_leftovers(self):
        html = (UI / "app.html").read_text("utf-8")
        self.assertNotRegex(html, r"Kobra Control|kobracontrol|kobra-boot|U1 Control|u1control|Snapmaker|Spoolman")

    def test_page_bundles_three(self):
        """three.js is in the page (the WebGL probe), and its licence travels in the wheel."""
        self.assertIn("WebGLRenderer", (ROOT / "ui" / "src" / "core" / "three-probe.ts").read_text("utf-8"))
        self.assertRegex((UI / "app.html").read_text("utf-8"), r"three\.js|WEBGL|webglcontextlost")
        self.assertIn("three.js authors", (ROOT / "ui" / "licenses" / "Three.txt").read_text("utf-8"))

    def test_app_uses_expected_icons(self):
        html = (UI / "app.html").read_text("utf-8")
        for name in ("folder", "settings", "warning", "magnet", "trash"):
            for part in self.shared_icon(name):
                self.assertIn(part, html, name)

    def test_no_unresolved_placeholders(self):
        self.assertIsNone(re.search(r"APP_HTML = '[^\n]*__ICONS__", self.text))
        self.assertNotIn("__ICONS__", build.page_html("app.html"))
        self.assertIn("__BOOT__", build.page_html("app.html"))   # filled per page by plugin.page_html

    def test_icons_are_plain_drawings(self):
        """The shared icons are data (element name and attributes), never markup that could run."""
        source = SHARED_ICONS.read_text("utf-8")
        tags = set(re.findall(r'\["([a-z]+)",\{', source))
        self.assertTrue(tags)
        self.assertLessEqual(tags, {"path", "circle", "rect", "line", "polyline", "polygon", "ellipse"})
        self.assertNotRegex(source, r"(?i)<script|\bon\w+\s*=|javascript:")

    def test_tab_icon_is_the_brand_tile(self):
        """The tab icon is assets/orca-cloud/embedder-tile.png at 64x64 (quantised PNG), and the wheel carries it."""
        data = (UI / "icon.png").read_bytes()
        self.assertEqual(data[:8], b"\x89PNG\r\n\x1a\n")
        self.assertEqual(struct.unpack(">II", data[16:24]), (64, 64))
        self.assertLess(len(data), 16_000)
        self.assertEqual(hashlib.sha256(data).hexdigest(), ICON_SHA256)   # re-exported from the tile: update both together
        self.assertIn("ICON_PNG = %r" % data, self.text)

    def test_built_size_reasonable(self):
        size = self.artifact.stat().st_size
        print("built size: %d bytes" % size)
        self.assertLess(size, MAX_BUILT_BYTES)


if __name__ == "__main__":
    unittest.main()
