"""Build the OrcaSlicer plugin as a pure-Python wheel: dist/embedder_any.whl.

Layout inside the wheel: embedder/__init__.py (plugin.py), one module per helper, and _assets.py
(the HTML page as a string constant, the PNG tab icon as bytes). The sources keep plain imports (`import settings`) so
they run and test in place; the build rewrites them to package-relative form in the wheel copies.
Nothing is executed or compiled at load time; the wheel is plain importable source. Zip timestamps
are fixed so equal sources give equal bytes.
"""

import ast
import argparse
import base64
import hashlib
import re
import tomllib
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "embedder"
MODULES = ("geometry", "presets", "pocket", "settings", "threemf", "session")  # dependency order
ASSETS = {"APP_HTML": "app.html", "ICON_PNG": "icon.png"}   # app.html: the compiled Vue page (ui/, npm run build); icon.png: the brand tile at 40x40 RGBA
# OrcaSlicer on Windows shows the page in WebView2, which renders a page over 2 MiB of base64 (1,572,864 bytes) blank.
PAGE_LIMIT = 1_572_864 * 9 // 10   # bytes of UTF-8, with 10% headroom


def page_html(name):
    """The committed build of the page (ui/, npm run build), as the wheel carries it."""
    return (SRC / "ui" / name).read_text("utf-8")


def third_party_licences():
    """The licence texts of what the page bundles: the shared foundation's (Vue, PrimeVue, PrimeUIX, Lucide, Manrope)
    and ours (three.js), sorted by file name."""
    return sorted([*(ROOT / "ui" / "shared" / "licenses").glob("*.txt"), *(ROOT / "ui" / "licenses").glob("*.txt")])


def relative_imports(source):
    """`import X` -> `from . import X`, `from X import` -> `from .X import` for our modules."""
    names = "|".join(MODULES)
    source = re.sub(r"^(\s*)import (%s)(?: as (\w+))?\s*$" % names,
                    lambda m: "%sfrom . import %s%s" % (m[1], m[2], " as " + m[3] if m[3] else ""), source, flags=re.M)
    return re.sub(r"^(\s*)from (%s) import " % names, r"\1from .\2 import ", source, flags=re.M)


def wheel_files(project):
    """{path inside the wheel: bytes}, without the dist-info."""
    version = project["version"]
    plugin = (SRC / "plugin.py").read_text("utf-8")
    if plugin.count('VERSION = "0.0.0-dev"') != 1:
        raise SystemExit("plugin.py must contain exactly one VERSION placeholder")
    plugin = plugin.replace('VERSION = "0.0.0-dev"', "VERSION = %r" % version)
    size = len(page_html("app.html").encode("utf-8"))
    if size > PAGE_LIMIT:
        raise SystemExit("app.html is %d bytes, over the %d-byte limit (90%% of WebView2's 1,572,864)" % (size, PAGE_LIMIT))
    sources = {"__init__": plugin, **{m: (SRC / (m + ".py")).read_text("utf-8") for m in MODULES}}
    assets = "".join("%s = %r\n" % (const, (SRC / "ui" / name).read_bytes() if name.endswith(".png") else page_html(name))
                     for const, name in ASSETS.items())
    # The notices also travel inside the plugin's own code: OrcaSlicer installs the package, not the dist-info.
    notices = {lic.stem: lic.read_text("utf-8") for lic in third_party_licences()}
    assets += "THIRD_PARTY_NOTICES = %r\n" % notices
    sources["_assets"] = ("# Generated by scripts/build.py from src/embedder/ui. The page bundles third-party code; its\n"
                          "# licence texts are in THIRD_PARTY_NOTICES (%s).\n" % ", ".join(notices)) + assets
    files = {}
    for name, text in sources.items():
        text = relative_imports(text) if name != "_assets" else text
        ast.parse(text, name + ".py")   # syntax check only
        files["embedder/%s.py" % name] = text.encode("utf-8")
    return files


def dist_info(project, files):
    di = "%s-%s.dist-info/" % (project["name"], project["version"])
    meta = {
        di + "METADATA": "\n".join([
            "Metadata-Version: 2.1",
            "Name: " + project["name"],
            "Version: " + project["version"],
            "Summary: " + project["description"],
            "Author: " + project["authors"][0]["name"],
            "License: " + project["license"],
            "Requires-Python: " + project["requires-python"],
            "",
        ]),
        di + "WHEEL": "Wheel-Version: 1.0\nGenerator: embedder scripts/build.py\nRoot-Is-Purelib: true\nTag: py3-none-any\n",
        di + "top_level.txt": "embedder\n",
    }
    meta = {k: v.encode("utf-8") for k, v in meta.items()}
    # the Vue page bundles Vue, PrimeVue, PrimeUIX, three.js, Lucide and Manrope: their notices travel with the wheel, next to our LICENSE
    meta[di + "licenses/LICENSE"] = (ROOT / "LICENSE").read_bytes()
    for lic in third_party_licences():
        meta[di + "licenses/" + lic.name] = lic.read_bytes()
    record = []
    for path, data in {**files, **meta}.items():
        digest = base64.urlsafe_b64encode(hashlib.sha256(data).digest()).rstrip(b"=").decode()
        record.append("%s,sha256=%s,%d" % (path, digest, len(data)))
    record.append(di + "RECORD,,")
    meta[di + "RECORD"] = ("\n".join(record) + "\n").encode("utf-8")
    return meta


def build(out_dir=ROOT / "dist", release_tag=None):
    project = tomllib.loads((ROOT / "pyproject.toml").read_text("utf-8"))["project"]
    if release_tag is not None and release_tag.lstrip("v") != project["version"]:
        raise SystemExit("tag %s does not match version %s" % (release_tag, project["version"]))
    files = wheel_files(project)
    files.update(dist_info(project, files))
    out_dir.mkdir(parents=True, exist_ok=True)
    artifact = out_dir / "embedder_any.whl"
    with zipfile.ZipFile(artifact, "w", zipfile.ZIP_DEFLATED) as z:
        for path, data in files.items():
            info = zipfile.ZipInfo(path, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, data)
    digest = hashlib.sha256(artifact.read_bytes()).hexdigest()
    (out_dir / "SHA256SUMS").write_text("%s  %s\n" % (digest, artifact.name), "utf-8")
    return artifact


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-tag")
    print(build(release_tag=parser.parse_args().release_tag))
